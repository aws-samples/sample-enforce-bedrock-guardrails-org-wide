import {
  App,
  Stack,
  StackProps,
  CfnOutput,
  DefaultStackSynthesizer,
} from 'aws-cdk-lib';
import { CfnStackSet } from 'aws-cdk-lib/aws-cloudformation';
import { Construct } from 'constructs';
import { BlogBenchmarkGuardrailStack } from './blog-guardrail-stack';

export interface BlogStackSetStackProps extends StackProps {
  /**
   * Regions to deploy the guardrail to. Bedrock guardrails are regional and
   * must be referenced from the same region the model is invoked in.
   * @default ['us-east-1', 'us-west-2']
   */
  readonly targetRegions?: string[];

  /**
   * Either OU IDs (recommended for SERVICE_MANAGED) or 12-digit account IDs
   * (for SELF_MANAGED). If empty, the StackSet is created without instances —
   * useful for review and approval workflows.
   * @default []
   */
  readonly targets?: string[];

  /** @default 'SERVICE_MANAGED' */
  readonly permissionModel?: 'SERVICE_MANAGED' | 'SELF_MANAGED';

  /**
   * AWS Organization ID, propagated to each member-stack guardrail so its
   * resource-based policy grants `bedrock:ApplyGuardrail` to org members.
   * Required for the org-level enforcement pattern.
   */
  readonly organizationId?: string;
}

/**
 * Multi-region, multi-account REPLICATION of the benchmark guardrail via
 * CloudFormation StackSets. Deploy this stack from the management account
 * or a registered delegated administrator for CloudFormation StackSets.
 *
 * IMPORTANT (CSR-013): this is NOT the same enforcement model as Layer 1
 * (the Bedrock Organizations policy). Layer 1 references ONE guardrail
 * owned by the management account and every member account calls that same
 * guardrail cross-account via a resource-based policy. This StackSet
 * instead deploys an INDEPENDENT COPY of the guardrail into every target
 * account/region — each member account ends up owning its own
 * `AWS::Bedrock::Guardrail` resource with the same configuration, not a
 * reference to a single shared one. That is unavoidable for regions (a
 * guardrail is a regional resource, so no single guardrail can serve every
 * region), but it is also true across accounts with this implementation.
 *
 * Use this stack when you want per-account/per-region guardrail replicas
 * with identical configuration (e.g. because you want each account to be
 * able to evolve its copy independently later, or you are not using the
 * org-policy pattern at all). Do not use it if your requirement is "exactly
 * one central guardrail enforced everywhere" — that requirement is met by
 * Layer 1 (bedrock-organizations-policy.json) referencing the single
 * guardrail this repo's `Blog-Benchmark-Guardrail` stack deploys, not by
 * this StackSet.
 *
 * The StackSet's TemplateBody is generated by synthesising the
 * BlogBenchmarkGuardrailStack into a side App, so each replica's template
 * is bit-identical to the single-region stack's template — only the
 * deployed resource identities differ per account/region.
 */
export class BlogStackSetStack extends Stack {
  public readonly stackSet: CfnStackSet;

  constructor(scope: Construct, id: string, props: BlogStackSetStackProps = {}) {
    super(scope, id, props);

    const targetRegions = props.targetRegions ?? ['us-east-1', 'us-west-2'];
    const targets = props.targets ?? [];
    const permissionModel = props.permissionModel ?? 'SERVICE_MANAGED';
    const orgId = props.organizationId;

    const templateBody = synthesizeMemberTemplate(orgId);

    const stackInstancesGroup =
      targets.length > 0
        ? [
            {
              regions: targetRegions,
              deploymentTargets:
                permissionModel === 'SERVICE_MANAGED'
                  ? { organizationalUnitIds: targets }
                  : { accounts: targets },
            },
          ]
        : undefined;

    this.stackSet = new CfnStackSet(this, 'BenchGuardrailStackSet', {
      stackSetName: 'blog-benchmark-guardrail',
      description:
        'Multi-region rollout of the benchmark guardrail referenced by the blog post.',
      permissionModel,
      capabilities: ['CAPABILITY_IAM'],
      autoDeployment:
        permissionModel === 'SERVICE_MANAGED'
          ? { enabled: true, retainStacksOnAccountRemoval: false }
          : undefined,
      operationPreferences: {
        failureToleranceCount: 0,
        maxConcurrentCount: 5,
        regionConcurrencyType: 'PARALLEL',
      },
      stackInstancesGroup,
      templateBody,
    });

    new CfnOutput(this, 'StackSetName', { value: 'blog-benchmark-guardrail' });
    new CfnOutput(this, 'TargetRegions', { value: targetRegions.join(',') });
    new CfnOutput(this, 'TargetCount', {
      value: String(targets.length),
      description: 'Number of OUs/accounts targeted (0 = template only)',
    });
  }
}

function synthesizeMemberTemplate(organizationId?: string): string {
  const innerApp = new App();
  const stack = new BlogBenchmarkGuardrailStack(innerApp, 'BenchMember', {
    synthesizer: new DefaultStackSynthesizer({ generateBootstrapVersionRule: false }),
    organizationId,
  });
  const assembly = innerApp.synth();
  const template = assembly.getStackArtifact(stack.artifactId).template;
  return JSON.stringify(template);
}
